import { memo, useCallback, useState, type ReactNode } from 'react';
import { Pressable, StyleSheet, View } from 'react-native';

import { AppText } from '@/components/ui';
import { useTranslation } from '@/i18n';
import { layout, makeStyles, radius, spacing, useTheme } from '@/theme';
import type { AiCourseSummaryDto } from '@/types/api';

import { BenefitsList } from './BenefitsList';
import { SparklesIcon } from './SparklesIcon';

export type AiSummaryContentProps = { summary: AiCourseSummaryDto };

/** Chapters shown before "See more" (a course can have up to 15). */
const COLLAPSED_SECTIONS = 4;

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <View style={styles.section}>
      <AppText variant="title" accessibilityRole="header">
        {title}
      </AppText>
      {children}
    </View>
  );
}

function BulletList({ items }: { items: readonly string[] }) {
  const themed = useStyles();
  return (
    <View style={styles.bullets}>
      {items.map((item) => (
        <View key={item} style={styles.bulletRow}>
          <View style={themed.bullet} />
          <AppText variant="body" style={styles.flex}>
            {item}
          </AppText>
        </View>
      ))}
    </View>
  );
}

/** The "Generated by AI" pill that labels every AI-written block. */
export function AiBadge() {
  const { t } = useTranslation('course');
  const { colors } = useTheme();
  const themed = useStyles();
  return (
    <View style={themed.badge}>
      <SparklesIcon size={13} color={colors.secondaryText} />
      <AppText variant="micro" color="secondaryText">
        {t('ai.generatedBy')}
      </AppText>
    </View>
  );
}

/** Overview, goals, chapter outline, audience and outcomes of the AI course summary (AI-03). */
function AiSummaryContentBase({ summary }: AiSummaryContentProps) {
  const { t } = useTranslation(['course', 'common']);
  const [isExpanded, setIsExpanded] = useState(false);
  const toggleExpanded = useCallback(() => setIsExpanded((value) => !value), []);
  const sections = isExpanded ? summary.sections : summary.sections.slice(0, COLLAPSED_SECTIONS);

  return (
    <View style={styles.content} testID="ai-summary-content">
      <AiBadge />
      <AppText variant="body" color="textSecondary">
        {summary.overview}
      </AppText>
      {summary.objectives.length > 0 ? (
        <Section title={t('course:ai.objectives')}>
          <BenefitsList benefits={summary.objectives} />
        </Section>
      ) : null}
      {summary.sections.length > 0 ? (
        <Section title={t('course:ai.outline')}>
          <View style={styles.outline}>
            {sections.map((section, index) => (
              <View key={`${index}-${section.title}`} style={styles.outlineRow}>
                <AppText variant="label" family="bodyBold">
                  {`${index + 1}. ${section.title}`}
                </AppText>
                <AppText variant="body" color="textSecondary">
                  {section.summary}
                </AppText>
              </View>
            ))}
          </View>
          {summary.sections.length > COLLAPSED_SECTIONS ? (
            <Pressable
              onPress={toggleExpanded}
              accessibilityRole="link"
              accessibilityState={{ expanded: isExpanded }}
              style={styles.toggle}
            >
              <AppText variant="caption" color="primaryText">
                {isExpanded ? t('common:actions.seeLess') : t('common:actions.seeMore')}
              </AppText>
            </Pressable>
          ) : null}
        </Section>
      ) : null}
      {summary.targetAudience.length > 0 ? (
        <Section title={t('course:ai.audience')}>
          <BulletList items={summary.targetAudience} />
        </Section>
      ) : null}
      {summary.outcomes.length > 0 ? (
        <Section title={t('course:ai.outcomes')}>
          <BenefitsList benefits={summary.outcomes} />
        </Section>
      ) : null}
      <AppText variant="caption">{t('course:ai.disclaimer')}</AppText>
    </View>
  );
}

const useStyles = makeStyles((t) => ({
  bullet: {
    width: 6,
    height: 6,
    borderRadius: radius.pill,
    marginTop: 8,
    marginLeft: spacing.xs,
    backgroundColor: t.colors.primaryText,
  },
  badge: {
    alignSelf: 'flex-start',
    flexDirection: 'row',
    alignItems: 'center',
    gap: spacing.xs,
    paddingHorizontal: spacing.md,
    paddingVertical: spacing.xs,
    borderRadius: radius.pill,
    backgroundColor: t.colors.secondarySoft,
  },
}));

const styles = StyleSheet.create({
  content: { gap: spacing.xl },
  section: { gap: spacing.md },
  outline: { gap: spacing.lg },
  outlineRow: { gap: spacing.xs },
  bullets: { gap: spacing.sm },
  bulletRow: { flexDirection: 'row', alignItems: 'flex-start', gap: spacing.md },
  flex: { flex: 1 },
  toggle: {
    minHeight: layout.minTouchTarget,
    justifyContent: 'center',
    alignSelf: 'flex-start',
  },
});

export const AiSummaryContent = memo(AiSummaryContentBase);
