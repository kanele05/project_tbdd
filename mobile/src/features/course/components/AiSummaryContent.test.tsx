import { fireEvent, render, screen } from '@testing-library/react-native';

import type { AiCourseSummaryDto } from '@/types/api';

import { AiSummaryContent } from './AiSummaryContent';

jest.mock('expo-router', () => ({
  router: { push: jest.fn(), back: jest.fn(), replace: jest.fn(), canGoBack: () => true },
}));

function makeSummary(sectionCount: number): AiCourseSummaryDto {
  return {
    courseId: 'c1',
    lang: 'en',
    overview: 'An overview.',
    objectives: ['Goal one', 'Goal two', 'Goal three'],
    sections: Array.from({ length: sectionCount }, (_, index) => ({
      title: `Chapter ${index + 1}`,
      summary: `About chapter ${index + 1}.`,
    })),
    targetAudience: ['Beginners', 'Designers'],
    outcomes: ['Outcome one', 'Outcome two', 'Outcome three'],
    model: 'mock-ai-1',
    generatedAt: '2026-10-04T00:00:00Z',
  };
}

describe('AiSummaryContent', () => {
  it('shows every block under its heading with the AI label and disclaimer', async () => {
    await render(<AiSummaryContent summary={makeSummary(2)} />);

    expect(screen.getByText('Generated by AI')).toBeOnTheScreen();
    expect(screen.getByText('An overview.')).toBeOnTheScreen();
    expect(screen.getByText('Learning goals')).toBeOnTheScreen();
    expect(screen.getByText('Chapter by chapter')).toBeOnTheScreen();
    expect(screen.getByText("Who it's for")).toBeOnTheScreen();
    expect(screen.getByText("What you'll achieve")).toBeOnTheScreen();
    expect(screen.getByText('Beginners')).toBeOnTheScreen();
    expect(screen.getByText(/AI can make mistakes/)).toBeOnTheScreen();
    expect(screen.queryByText('See more')).not.toBeOnTheScreen();
  });

  it('collapses a long outline to 4 chapters and expands it with See more', async () => {
    await render(<AiSummaryContent summary={makeSummary(7)} />);

    expect(screen.getByText('4. Chapter 4')).toBeOnTheScreen();
    expect(screen.queryByText('5. Chapter 5')).not.toBeOnTheScreen();

    await fireEvent.press(screen.getByText('See more'));
    expect(screen.getByText('7. Chapter 7')).toBeOnTheScreen();

    await fireEvent.press(screen.getByText('See less'));
    expect(screen.queryByText('5. Chapter 5')).not.toBeOnTheScreen();
  });

  it('skips empty blocks instead of rendering bare headings', async () => {
    await render(
      <AiSummaryContent
        summary={{ ...makeSummary(0), objectives: [], targetAudience: [], outcomes: [] }}
      />,
    );

    expect(screen.queryByText('Learning goals')).not.toBeOnTheScreen();
    expect(screen.queryByText('Chapter by chapter')).not.toBeOnTheScreen();
    expect(screen.queryByText("Who it's for")).not.toBeOnTheScreen();
  });
});
